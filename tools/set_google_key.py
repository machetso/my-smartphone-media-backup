#!/usr/bin/env python3
"""Write the app's Google key (OAuth client "Desktop app") to phonebackup/_gkey.py (git-ignored).

  python3 tools/set_google_key.py client_secret_XXXX.json      # file downloaded from Google Cloud
  python3 tools/set_google_key.py --id ID --secret SECRET      # used by the release workflow
"""
import argparse
import json
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("json_file", nargs="?")
ap.add_argument("--id")
ap.add_argument("--secret", default="")
a = ap.parse_args()
if a.json_file:
    d = json.loads(Path(a.json_file).read_text(encoding="utf-8"))
    d = d.get("installed") or d.get("web") or d
    cid, sec = d["client_id"], d.get("client_secret", "")
else:
    cid, sec = a.id, a.secret
if not cid or not cid.endswith(".apps.googleusercontent.com"):
    raise SystemExit("This does not look like a Google OAuth client ID.")
out = Path(__file__).resolve().parent.parent / "phonebackup" / "_gkey.py"
out.write_text("# generated by tools/set_google_key.py - NOT in git\n"
               f"CLIENT_ID = {cid!r}\nCLIENT_SECRET = {sec!r}\n", encoding="utf-8")
print(f"Google key written to {out}")
